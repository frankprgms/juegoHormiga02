
package entidades;

public class EstadisticasEntidad {
    
    private int agresividad;
    private int alcance;
    private int capacidadTransporte;
    private int edad;
    private int energia;
    private int fuerza;
    private int inteligencia;
    private int lealtad;
    private int nivel;
    private int nombre;
    private int resistenciaMax;
    private int saludMax;
    private int velocidad;

    public EstadisticasEntidad(int agresividad, int alcance, int capacidadTransporte, int edad, int energia, int fuerza, int inteligencia, int lealtad, int nivel, int nombre, int resistenciaMax, int saludMax, int velocidad) {
        this.agresividad = agresividad;
        this.alcance = alcance;
        this.capacidadTransporte = capacidadTransporte;
        this.edad = edad;
        this.energia = energia;
        this.fuerza = fuerza;
        this.inteligencia = inteligencia;
        this.lealtad = lealtad;
        this.nivel = nivel;
        this.nombre = nombre;
        this.resistenciaMax = resistenciaMax;
        this.saludMax = saludMax;
        this.velocidad = velocidad;
    }

    public int getAgresividad() {
        return agresividad;
    }

    public void setAgresividad(int agresividad) {
        this.agresividad = agresividad;
    }

    public int getAlcance() {
        return alcance;
    }

    public void setAlcance(int alcance) {
        this.alcance = alcance;
    }

    public int getCapacidadTransporte() {
        return capacidadTransporte;
    }

    public void setCapacidadTransporte(int capacidadTransporte) {
        this.capacidadTransporte = capacidadTransporte;
    }

    public int getEdad() {
        return edad;
    }

    public void setEdad(int edad) {
        this.edad = edad;
    }

    public int getEnergia() {
        return energia;
    }

    public void setEnergia(int energia) {
        this.energia = energia;
    }

    public int getFuerza() {
        return fuerza;
    }

    public void setFuerza(int fuerza) {
        this.fuerza = fuerza;
    }

    public int getInteligencia() {
        return inteligencia;
    }

    public void setInteligencia(int inteligencia) {
        this.inteligencia = inteligencia;
    }

    public int getLealtad() {
        return lealtad;
    }

    public void setLealtad(int lealtad) {
        this.lealtad = lealtad;
    }

    public int getNivel() {
        return nivel;
    }

    public void setNivel(int nivel) {
        this.nivel = nivel;
    }

    public int getNombre() {
        return nombre;
    }

    public void setNombre(int nombre) {
        this.nombre = nombre;
    }

    public int getResistenciaMax() {
        return resistenciaMax;
    }

    public void setResistenciaMax(int resistenciaMax) {
        this.resistenciaMax = resistenciaMax;
    }

    public int getSaludMax() {
        return saludMax;
    }

    public void setSaludMax(int saludMax) {
        this.saludMax = saludMax;
    }

    public int getVelocidad() {
        return velocidad;
    }

    public void setVelocidad(int velocidad) {
        this.velocidad = velocidad;
    }
    

    
}
